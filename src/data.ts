export const products: Product[] = productRows.map((row, index) => {
  const discount = [8, 12, 15, 20, 10, 18][index % 6];
  return {
    id: row[0],
    name: row[1],
    category: row[2],
    brand: row[3],
    price: row[4],
    originalPrice: Math.round(row[4] / (1 - discount / 100) / 1000) * 1000,
    discount,
    stock: index % 11 === 0 ? 3 : 8 + ((index * 7) % 35),
    spec: row[5],
    warranty: row[6],
    rating: 4.5 + (index % 5) / 10,
    sold: 82 + ((index * 137) % 2200),
    isNew: index % 8 === 0,
  };
});

